"""Audio-level eval harness — the practical substitute for a real Coval
integration (TESTING.md's Coval tooling needs a Coval account/API key we
don't have; this is honest about that gap, see the module docstring below).

Runs audio-samples/*.wav (generated by audio_gen/generate_samples.py) through
Deepgram's prerecorded STT -> the SAME call_parser.parse_call /
mismatch.check_mismatch code the live/scenario server paths use -> scores
against each clip's ground truth, and writes a pass/fail scorecard.

Coval gap, stated plainly: TESTING.md calls for "Pipecat -> Coval
integration" specifically. Coval (coval.dev) is a third-party hosted eval
product requiring its own account/API key, which this build does not have.
What's built here instead is a local, Deepgram-grounded eval harness that
covers the same synthetic test classes (docs/TESTING.md #2) and the same
metrics (docs/TESTING.md #3) using Pipecat's own installed `pipecat.evals`
primitives are NOT used here either — wiring a full simulated bot through
that framework needs a running transport + judge LLM and was more machinery
than this scoped eval needed. If/when a COVAL_API_KEY exists, swap
`transcribe_file` below for Coval's ingestion API; the scoring logic and
ground-truth manifest don't need to change.

Two modes:
  --mode deepgram   (default if DEEPGRAM_API_KEY is set) real STT, real numbers.
  --mode mock       uses the ground-truth text directly (no audio decoding at
                     all) so the SCORING LOGIC ITSELF is verified without a key.
                     Every number produced in mock mode is trivially 100% —
                     it proves the harness works, not that the audio pipeline does.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
import time
from dataclasses import dataclass, field
from pathlib import Path

from app.call_parser import parse_call
from eval.deepgram_prerecorded import transcribe_file

AUDIO_DIR = Path(__file__).resolve().parent.parent.parent / "audio-samples"
MANIFEST_PATH = AUDIO_DIR / "manifest.json"
SCORECARD_PATH = AUDIO_DIR / "scorecard.md"


@dataclass
class ClipResult:
    name: str
    mode: str
    latency_s: float
    expected: list[dict]
    actual: list[dict]
    matched_expected: int = 0
    missed_calls: int = 0
    false_triggers: int = 0
    notes: list[str] = field(default_factory=list)


def _matches(expected: dict, actual: dict) -> bool:
    if expected.get("item") != actual.get("item"):
        return False
    if expected.get("item") is not None and expected.get("quantity") != actual.get("quantity"):
        return False
    exp_station = expected.get("station")
    return exp_station is None or exp_station == actual.get("station")


def _score(name: str, mode: str, latency_s: float, expected: list[dict], utterances: list[tuple[str, str]]) -> ClipResult:
    actual = []
    for speaker_turn, text in utterances:
        call = parse_call(text, speaker_turn=speaker_turn)
        actual.append({"item": call.item, "quantity": call.quantity, "station": call.station, "is_call": call.is_call, "text": text})

    result = ClipResult(name=name, mode=mode, latency_s=latency_s, expected=expected, actual=actual)
    used = [False] * len(actual)

    for exp in expected:
        exp_is_call = exp.get("is_call", True)
        hit = False
        for i, act in enumerate(actual):
            if used[i]:
                continue
            if not exp_is_call and not act["is_call"]:
                used[i] = True
                hit = True
                break
            if exp_is_call and act["is_call"] and _matches(exp, act):
                used[i] = True
                hit = True
                break
        if hit:
            result.matched_expected += 1
        elif exp_is_call:
            result.missed_calls += 1
            result.notes.append(f"MISSED: expected {exp}")
        else:
            result.notes.append(f"chatter not suppressed as expected: {exp}")

    for i, act in enumerate(actual):
        if not used[i] and act["is_call"]:
            result.false_triggers += 1
            result.notes.append(f"FALSE TRIGGER: parsed a call not in ground truth: {act}")

    return result


async def run(mode: str) -> list[ClipResult]:
    manifest = json.loads(MANIFEST_PATH.read_text())
    results = []
    for entry in manifest:
        wav_path = AUDIO_DIR / entry["file"]
        start = time.monotonic()
        if mode == "deepgram":
            utterances = await transcribe_file(str(wav_path))
        else:
            # mock: skip audio decoding entirely, feed ground-truth text straight through.
            utterances = [(f"speaker-{i}", c["text"]) for i, c in enumerate(entry["expected_calls"])]
        latency_s = time.monotonic() - start
        results.append(_score(entry["name"], mode, latency_s, entry["expected_calls"], utterances))
    return results


def write_scorecard(results: list[ClipResult]) -> None:
    total_expected_calls = sum(len([e for e in r.expected if e.get("is_call", True)]) for r in results)
    total_missed = sum(r.missed_calls for r in results)
    total_false = sum(r.false_triggers for r in results)
    accuracy = 1 - (total_missed / total_expected_calls) if total_expected_calls else 1.0

    lines = [
        "# kitchen-copilot audio eval scorecard",
        "",
        f"Mode: **{results[0].mode if results else 'n/a'}**"
        + ("  _(mock mode — proves the scoring harness, not the audio pipeline; see run_eval.py docstring)_"
           if results and results[0].mode == "mock" else ""),
        "",
        f"- Call-parse accuracy: **{accuracy:.0%}** ({total_expected_calls - total_missed}/{total_expected_calls} expected calls correctly extracted)",
        f"- False-trigger count: **{total_false}**",
        f"- Missed-call count: **{total_missed}**",
        f"- Mean per-clip latency: **{sum(r.latency_s for r in results) / len(results):.3f}s**" if results else "",
        "",
        "| Clip | Pass? | Missed | False triggers | Latency (s) |",
        "|---|---|---|---|---|",
    ]
    for r in results:
        passed = "✅" if r.missed_calls == 0 and r.false_triggers == 0 else "❌"
        lines.append(f"| {r.name} | {passed} | {r.missed_calls} | {r.false_triggers} | {r.latency_s:.3f} |")

    for r in results:
        if r.notes:
            lines.append(f"\n**{r.name}** notes:")
            lines.extend(f"- {n}" for n in r.notes)

    SCORECARD_PATH.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["deepgram", "mock"], default=None)
    args = parser.parse_args()
    mode = args.mode or ("deepgram" if "DEEPGRAM_API_KEY" in os.environ else "mock")

    results = asyncio.run(run(mode))
    write_scorecard(results)
    print(f"Ran {len(results)} clips in {mode} mode. Scorecard written to {SCORECARD_PATH}")
    for r in results:
        print(f"  {r.name}: missed={r.missed_calls} false_triggers={r.false_triggers} latency={r.latency_s:.3f}s")
